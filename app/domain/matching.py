def calculate_match_score(
    adopter: AdopterFacts, animal: AnimalFacts, direction: MatchDirection
) -> MatchScore:
    """Score one adopter against one animal in the requested direction.

    Reads as the specification does: check hard constraints, score each
    criterion, then combine using the weights for this direction.

    Args:
        adopter: The adopter's facts.
        animal: The animal's facts.
        direction: Which weighting to apply. The two directions deliberately
            differ (spec section 9).

    Returns:
        The score with its full per-criterion breakdown. Disqualified results
        carry a reason and an empty breakdown.
    """
    violation = find_hard_constraint_violation(adopter, animal)
    if violation is not None:
        return MatchScore.disqualified(direction, violation)

    weights = weights_for(direction)
    scored_criteria = tuple(
        _apply_weight(ALL_CRITERION_FUNCTIONS[criterion](adopter, animal), weight)
        for criterion, weight in weights.items()
    )

    total = sum(criterion.weighted_contribution for criterion in scored_criteria)

    return MatchScore(
        direction=direction,
        score=round(total),
        is_disqualified=False,
        disqualification_reason=None,
        criterion_scores=scored_criteria,
    )


def weights_for(direction: MatchDirection) -> dict[Criterion, float]:
    """Return the weight set for a direction."""
    if direction is MatchDirection.ADOPTER_TO_ANIMAL:
        return ADOPTER_TO_ANIMAL_WEIGHTS
    return ANIMAL_TO_ADOPTER_WEIGHTS


def _apply_weight(criterion_score: CriterionScore, weight: float) -> CriterionScore:
    """Attach the direction's weight to a criterion result.

    Criterion functions do not know which direction they are being used for,
    which keeps each one testable in isolation.
    """
    return CriterionScore(
        criterion=criterion_score.criterion,
        score=criterion_score.score,
        weight=weight,
        explanation=criterion_score.explanation,
    )


def rank_animals_for_adopter(
    adopter: AdopterFacts, animals: dict[str, AnimalFacts]
) -> list[tuple[str, MatchScore]]:
    """Rank animals for one adopter, best first (Find My Pet).

    Args:
        adopter: The adopter's facts.
        animals: Animal facts keyed by animal identifier.

    Returns:
        Identifier and score pairs, disqualified candidates excluded, ordered
        by descending score then by identifier so ties are stable.
    """
    return _rank(
        {key: calculate_match_score(adopter, facts, MatchDirection.ADOPTER_TO_ANIMAL)
         for key, facts in animals.items()}
    )


def rank_adopters_for_animal(
    animal: AnimalFacts, adopters: dict[str, AdopterFacts]
) -> list[tuple[str, MatchScore]]:
    """Rank adopters for one animal, best first (Find My Adopter).

    Args:
        animal: The animal's facts.
        adopters: Adopter facts keyed by adopter profile identifier.

    Returns:
        Identifier and score pairs, disqualified candidates excluded, ordered
        by descending score then by identifier so ties are stable.
    """
    return _rank(
        {key: calculate_match_score(facts, animal, MatchDirection.ANIMAL_TO_ADOPTER)
         for key, facts in adopters.items()}
    )


def _rank(scores: dict[str, MatchScore]) -> list[tuple[str, MatchScore]]:
    """Drop disqualified candidates and order the rest deterministically.

    Ties break on the identifier so that repeated runs over the same data
    produce the same order - important for stable screenshots and tests.
    """
    qualified = [(key, score) for key, score in scores.items() if not score.is_disqualified]
    return sorted(qualified, key=lambda pair: (-pair[1].score, pair[0]))

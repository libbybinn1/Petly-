/* ==========================================================================
   PetMatch - progressive enhancement, and nothing else.

   Every screen works with this file blocked: forms submit, dependent fields
   are visible, the theme follows the operating system and a pending analysis
   is reachable through its Refresh link. This file only makes those things
   pleasanter. No build step, no framework, no dependencies (spec section 30).

   Four behaviours, each opted into from a template by one attribute:
     [data-theme-choice]        light / dark / system theme buttons
     form[data-confirm]         confirm before a destructive submit
     [data-shown-by="<id>"]     reveal a region when a checkbox is ticked
     [data-analysis-status-url] poll for finished agent explanations
   ========================================================================== */
(function () {
  "use strict";

  var THEME_KEY = "petmatch-theme";

  /** Read a stored string, treating unavailable storage as "nothing stored". */
  function readStored(key) {
    try {
      return window.localStorage.getItem(key);
    } catch (error) {
      return null;
    }
  }

  /** Store a string, or remove the key when the value is null. */
  function writeStored(key, value) {
    try {
      if (value === null) {
        window.localStorage.removeItem(key);
      } else {
        window.localStorage.setItem(key, value);
      }
    } catch (error) {
      /* Private window or blocked site data: the choice lasts this page. */
    }
  }

  /* ---------------------------------------------- theme: light/dark/system */

  /** Apply a theme choice to the document and to the toggle's pressed state. */
  function applyTheme(choice) {
    var root = document.documentElement;
    if (choice === "light" || choice === "dark") {
      root.setAttribute("data-theme", choice);
    } else {
      root.removeAttribute("data-theme");   /* back to prefers-color-scheme */
    }
    document.querySelectorAll("[data-theme-choice]").forEach(function (button) {
      var pressed = button.getAttribute("data-theme-choice") === (choice || "system");
      button.setAttribute("aria-pressed", pressed ? "true" : "false");
    });
  }

  function initTheme() {
    var buttons = document.querySelectorAll("[data-theme-choice]");
    if (!buttons.length) {
      return;
    }
    applyTheme(readStored(THEME_KEY) || "system");
    buttons.forEach(function (button) {
      button.addEventListener("click", function () {
        var choice = button.getAttribute("data-theme-choice");
        writeStored(THEME_KEY, choice === "system" ? null : choice);
        applyTheme(choice);
      });
    });
  }

  /* ------------------------------------- confirm a destructive submission */

  /* Withdrawing an application and declining an invitation are both one
     click and both irreversible. The server is still the authority; this is
     only a chance to notice. */
  function initConfirmations() {
    document.querySelectorAll("form[data-confirm]").forEach(function (form) {
      form.addEventListener("submit", function (event) {
        if (!window.confirm(form.getAttribute("data-confirm"))) {
          event.preventDefault();
        }
      });
    });
  }

  /* ----------------------------------------------- progressive disclosure */

  /* A region marked `data-shown-by="<checkbox id>"` follows that checkbox.
     Without JavaScript the region is simply always visible, which is the
     behaviour every form on the site has today - never hidden content a
     visitor cannot reach. */
  function initDisclosure() {
    document.querySelectorAll("[data-shown-by]").forEach(function (region) {
      var trigger = document.getElementById(region.getAttribute("data-shown-by"));
      if (!trigger) {
        return;
      }
      var sync = function () {
        region.hidden = !trigger.checked;
      };
      trigger.addEventListener("change", sync);
      sync();
    });
  }

  /* --------------------------------------------- pending analysis polling */

  var POLL_FAST_MS = 8000;
  var POLL_SLOW_MS = 30000;
  var BACK_OFF_AFTER_MS = 120000;

  /* Explanations are generated by a separate process on CPU-only hardware, so
     a page can open before they exist (CLAUDE.md R4). Rather than make the
     visitor guess when to reload, poll the status endpoint and reload once
     something has actually changed. Backs off after two minutes, and stops
     dead on any failure - including the 404 it gets while the endpoint is
     still being built. */
  function initAnalysisPolling() {
    var marker = document.querySelector("[data-analysis-status-url]");
    if (!marker) {
      return;                     /* no pending work on this page: never poll */
    }

    var statusUrl = marker.getAttribute("data-analysis-status-url");
    var startedAt = Date.now();
    var lastGeneration = null;
    var lastPending = null;

    function schedule() {
      var elapsed = Date.now() - startedAt;
      window.setTimeout(poll, elapsed > BACK_OFF_AFTER_MS ? POLL_SLOW_MS : POLL_FAST_MS);
    }

    function poll() {
      window.fetch(statusUrl, {
        headers: { Accept: "application/json" },
        credentials: "same-origin"
      }).then(function (response) {
        return response.ok ? response.json() : null;
      }).then(function (status) {
        if (!status) {
          return;                 /* non-200: stop, and stay quiet about it */
        }
        var regenerated = lastGeneration !== null && status.generation !== lastGeneration;
        var drained = lastPending !== null && lastPending > 0 && status.pending === 0;
        if (regenerated || drained) {
          window.location.reload();
          return;
        }
        lastGeneration = status.generation;
        lastPending = status.pending;
        schedule();
      }).catch(function () {
        /* Offline, blocked, or malformed JSON: stop polling. */
      });
    }

    schedule();
  }

  function start() {
    initTheme();
    initConfirmations();
    initDisclosure();
    initAnalysisPolling();
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", start);
  } else {
    start();
  }
})();
